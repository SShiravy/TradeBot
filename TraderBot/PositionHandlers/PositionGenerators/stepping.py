from ChartModule.models import Chart, Signal
from TraderBot.PositionHandlers.manager import PositionGenerator
import TraderBot.Commands as commands
from TraderBot.events import StopLossHit, TakeProfitHit
from TraderBot.models import (
    PositionSide,
    Position,
    PositionType,
    Trigger,
)
from abc import abstractmethod
import logging


logger = logging.getLogger("PositionManager")


class SteppingGenerator(PositionGenerator):
    def __init__(
        self,
        leverage: int,
        tp_ratio: list[float],
        tp_ratio_volumes: list[float],
        fixed_tp_volumes: list[float],
        trail_stop: bool,
    ) -> None:
        if len(tp_ratio) != len(tp_ratio_volumes):
            raise ValueError(
                f"tp_ratio_volumes param must be \
                             list[float] with same size as tp_ratio\
                             {len(tp_ratio_volumes)} != {len(tp_ratio)}"
            )

        initial_volume = round(sum(tp_ratio_volumes) + sum(fixed_tp_volumes), 2)
        super().__init__(initial_volume, leverage)
        self.trail_stop = trail_stop
        self.tp_ratio = tp_ratio
        self.tp_ratio_volumes = tp_ratio_volumes

    @abstractmethod
    def stoploss_price(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> float:
        pass

    @abstractmethod
    def fixed_tps(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> list[tuple[float, float]]:
        """returns (price, volume) of each fixed-distance tp"""
        pass

    def init_stoploss(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> Trigger:
        return Trigger(
            price=round(
                self.stoploss_price(entry_price, side, chart), chart.precision
            ),
            event=StopLossHit(),
            volume=self.initial_volume,
            cross_direction=side.factor * -1,
        )

    def generate_triggers(
        self,
        entry_price: float,
        side: PositionSide,
        sl_price: float,
        chart: Chart,
    ) -> list[Trigger]:
        steps: list[Trigger] = []
        for price, volume in self.fixed_tps(entry_price, side, chart):
            steps.append(
                Trigger(
                    price=round(price, chart.precision),
                    event=TakeProfitHit(),
                    volume=volume,
                    cross_direction=side.factor,
                )
            )

        sl_distance = abs(sl_price - entry_price)
        for ratio, volume in zip(self.tp_ratio, self.tp_ratio_volumes):
            steps.append(
                Trigger(
                    price=round(
                        entry_price + sl_distance * ratio * side.factor, chart.precision
                    ),
                    event=TakeProfitHit(),
                    volume=volume,
                    cross_direction=side.factor,
                )
            )

        steps.sort(key=lambda t: t.price * side.factor)
        if self.trail_stop:
            for i, step in enumerate(steps):
                previous_price = steps[i - 1].price if i > 0 else entry_price
                step.event.trail_stop = previous_price  # type:ignore

        return steps

    def export_config(self) -> dict:
        return {
            "Handler": self.__class__.__name__,
            "initial_volume": self.initial_volume,
            "leverage": self.leverage,
            "tp_ratio": self.tp_ratio,
            "tp_ratio_volumes": self.tp_ratio_volumes,
        }

    def generate(
        self,
        signal: Signal,
        entry_price: float,
        **kwargs,
    ) -> Position | None:
        """
        set sl_base_price parameter if needed
        """
        side = PositionSide.convert_market_side(signal.side)
        sl_base_price = kwargs.get("sl_base_price", entry_price)
        sl = self.init_stoploss(sl_base_price, side, signal.chart)
        triggers = self.generate_triggers(entry_price, side, sl.price, signal.chart)
        position = Position(
            signal.chart,
            side,
            entry_price,
            self.initial_volume,
            triggers,
            sl,
            self.leverage,
            type=PositionType.MARKET,
            source=signal.source,
        )

        logger.info(
            f"New Position on {position.chart} Generated by {self.__class__.__name__}"
        )
        return position


class ForexStepping(SteppingGenerator):
    def __init__(
        self,
        leverage: int = 1,
        sl_pip: int = 5,
        tp_ratio: list[float] = [1, 2, 3],
        tp_ratio_volumes: list[float] = [0.01, 0.01, 0.01],
        tp_pip: list[float] = [],
        tp_pip_volumes: list[float] = [],
        trail_stop: bool = True,
    ) -> None:
        if len(tp_pip) != len(tp_pip_volumes):
            raise ValueError(
                f"tp_volumes_lot param must be {tp_pip}\
                             float or list[float] with same size as tp_pip\
                             {len(tp_pip_volumes)} != {len(tp_pip)}"
            )

        super().__init__(
            leverage, tp_ratio, tp_ratio_volumes, tp_pip_volumes, trail_stop
        )
        self.sl_pip = sl_pip
        self.tp_pip = tp_pip
        self.tp_pip_volumes = tp_pip_volumes

    def stoploss_price(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> float:
        return entry_price - side.factor * self.sl_pip * chart.pip_factor

    def fixed_tps(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> list[tuple[float, float]]:
        return [
            (entry_price + pip * side.factor * chart.pip_factor, volume)
            for pip, volume in zip(self.tp_pip, self.tp_pip_volumes)
        ]

    def export_config(self) -> dict:
        return super().export_config() | {
            "sl_pip": self.sl_pip,
            "tp_pip": self.tp_pip,
            "tp_pip_volumes": self.tp_pip_volumes,
        }


class CryptoStepping(SteppingGenerator):
    def __init__(
        self,
        leverage: int = 1,
        sl_percent: float = 1,
        tp_ratio: list[float] = [1, 2, 3],
        tp_ratio_volumes: list[float] = [1,1,1],
        tp_percent: list[float] = [],
        tp_percent_volumes: list[float] = [],
        trail_stop: bool = True,
    ) -> None:
        if len(tp_percent) != len(tp_percent_volumes):
            raise ValueError(
                f"tp_percent_volumes param must be \
                             list[float] with same size as tp_percent\
                             {len(tp_percent_volumes)} != {len(tp_percent)}"
            )

        super().__init__(
            leverage, tp_ratio, tp_ratio_volumes, tp_percent_volumes, trail_stop
        )
        self.sl_percent = sl_percent
        self.tp_percent = tp_percent
        self.tp_percent_volumes = tp_percent_volumes

    def stoploss_price(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> float:
        return entry_price * (1 - side.factor * self.sl_percent / 100)

    def fixed_tps(
        self, entry_price: float, side: PositionSide, chart: Chart
    ) -> list[tuple[float, float]]:
        return [
            (entry_price * (1 + side.factor * percent / 100), volume)
            for percent, volume in zip(self.tp_percent, self.tp_percent_volumes)
        ]

    def export_config(self) -> dict:
        return super().export_config() | {
            "sl_percent": self.sl_percent,
            "tp_percent": self.tp_percent,
            "tp_percent_volumes": self.tp_percent_volumes,
        }
